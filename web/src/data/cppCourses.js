/** 从完整课程名提取上课主题短名，例如「第 1 章-并查集-第 2 课 并查集应用--最小生成树」→「并查集应用--最小生成树」 */
export function shortTopicName(name) {
  const raw = String(name || '').trim();
  if (!raw) return '';
  const matches = [...raw.matchAll(/第\s*\d+\s*课[-\s]*/g)];
  if (matches.length) {
    return raw.slice(matches[matches.length - 1].index + matches[matches.length - 1][0].length).replace(/^[-—\s]+/, '').trim() || raw;
  }
  return raw.replace(/^第\s*\d+\s*章-/, '').trim() || raw;
}

export function lessonsOfTrack(trackId) {
  return CPP_LESSONS[trackId] || [];
}

export function findLesson(trackId, lessonIndex) {
  const idx = Number(lessonIndex);
  return lessonsOfTrack(trackId).find((item) => item.index === idx) || null;
}
